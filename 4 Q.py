import numpy as np

a = np.array([1,2,3])
b = np.array([4,5,6])

# Addition
print("Addition:", a + b)

# Subtraction
print("Subtraction:", a - b)

# Multiplication
print("Multiplication:", a * b)

# Division
print("Division:", a / b)

# Power of 3
print("Power of 3:", a ** 3)

# Square
print("Square:", a ** 2)

# Mean
print("Mean:", np.mean(a))